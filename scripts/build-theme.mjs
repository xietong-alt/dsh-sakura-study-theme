import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { inspectMedia, MAX_VIDEO_SECONDS } from './media.mjs';
import { activateTheme } from '../src/runtime.mjs';

export const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function validateConfig(config) {
  if (!config || typeof config !== 'object' || Array.isArray(config)) throw new Error('Configuration must be an object.');
  if (typeof config.wallpaper !== 'string' || !config.wallpaper.trim()) throw new Error('wallpaper must be a file path.');
  for (const key of ['dimTop', 'dimBottom', 'sidebarOpacity', 'composerOpacity']) {
    if (!Number.isFinite(config[key]) || config[key] < 0 || config[key] > 1) throw new Error(`${key} must be between 0 and 1.`);
  }
  for (const key of ['sidebarBlur', 'composerBlur']) {
    if (!Number.isFinite(config[key]) || config[key] < 0 || config[key] > 48) throw new Error(`${key} must be between 0 and 48 pixels.`);
  }
}

export async function buildTheme({ image, media, out = projectRoot, config: overrides = {} } = {}) {
  if (image && media) throw new Error('Pass only one of --image or --media.');
  const config = { ...JSON.parse(await fs.readFile(path.join(projectRoot, 'theme.config.json'), 'utf8')), ...overrides };
  validateConfig(config);
  const imagePath = media || image ? path.resolve(media || image) : path.resolve(projectRoot, config.wallpaper);
  const bytes = await fs.readFile(imagePath);
  if (bytes.length > 32 * 1024 * 1024) throw new Error('Media must be no larger than 32 MiB.');
  const type = inspectMedia(bytes);
  const output = path.resolve(out);
  if (output !== projectRoot && projectRoot.startsWith(output + path.sep)) throw new Error('Output cannot be an ancestor of this project.');
  const asset = `assets/wallpaper.${type.extension}`;
  const palette = await fs.readFile(path.join(projectRoot, 'styles/dark-palette.css'), 'utf8');
  const baseCss = await fs.readFile(path.join(projectRoot, 'styles/theme.css'), 'utf8');
  const mediaCss = await fs.readFile(path.join(projectRoot, 'styles/media.css'), 'utf8');
  const material = `
html body[data-sakura-study]{--dsw-specific-sidebar-fill:rgba(18,20,34,${config.sidebarOpacity}) !important;--dsw-specific-input-major:rgba(80,74,88,${config.composerOpacity}) !important;}
html body[data-sakura-study]{--sakura-dim-top:${config.dimTop};--sakura-dim-bottom:${config.dimBottom};}
body[data-sakura-study] .mP3x-q_sidebarCol{backdrop-filter:blur(${config.sidebarBlur}px) saturate(110%) !important;-webkit-backdrop-filter:blur(${config.sidebarBlur}px) saturate(110%) !important;}
body[data-sakura-study] .GRgSLq_card{backdrop-filter:blur(${config.composerBlur}px) saturate(115%) !important;-webkit-backdrop-filter:blur(${config.composerBlur}px) saturate(115%) !important;}
@media(prefers-reduced-transparency:reduce){html body[data-sakura-study]{--dsw-specific-sidebar-fill:rgba(18,20,34,.9) !important;--dsw-specific-input-major:rgba(50,46,62,.95) !important;}body[data-sakura-study] .mP3x-q_sidebarCol,body[data-sakura-study] .GRgSLq_card{backdrop-filter:none !important;-webkit-backdrop-filter:none !important;}}
`;
  const css = `${palette}\n${baseCss}\n${mediaCss}\n${material}`;
  const runtimeOptions = { css, maxVideoSeconds: MAX_VIDEO_SECONDS, media: { ...type, uri: `data:${type.mime};base64,${bytes.toString('base64')}` } };
  const client = `// Generated by scripts/build-theme.mjs; edit source styles/configuration instead.\nwindow.__ModuleLoader__.load({id:'dsh-sakura-study-theme',factory(require){\nconst React=require('react');\nconst activateTheme=${activateTheme.toString()};\nreturn {inject:['slots'],apply(ctx){activateTheme(ctx,${JSON.stringify(runtimeOptions)},React);}};\n}});\n`;
  const manifest = JSON.parse(await fs.readFile(path.join(projectRoot, 'package.json'), 'utf8'));
  if (output !== projectRoot) {
    await fs.mkdir(output, { recursive: true });
    for (const file of ['index.js', 'cordis.patch.yml', 'icon.svg', 'README.md', 'LICENSE', 'ASSET_LICENSE.md', 'THIRD_PARTY_LICENSES.txt', 'locale/en.json', 'locale/zh.json', 'styles/theme.css', 'styles/dark-palette.css', 'styles/media.css']) {
      await fs.mkdir(path.dirname(path.join(output, file)), { recursive: true });
      await fs.copyFile(path.join(projectRoot, file), path.join(output, file));
    }
    delete manifest.scripts;
    manifest.files = ['index.js', 'client.js', 'cordis.patch.yml', 'icon.svg', 'locale/*.json', 'styles/*.css', asset, 'theme.config.json', 'README.md', 'LICENSE', 'ASSET_LICENSE.md', 'THIRD_PARTY_LICENSES.txt'];
    await fs.writeFile(path.join(output, 'package.json'), JSON.stringify(manifest, null, 2) + '\n');
  }
  await fs.mkdir(path.join(output, 'assets'), { recursive: true });
  if (path.resolve(imagePath) !== path.resolve(output, asset)) await fs.writeFile(path.join(output, asset), bytes);
  await fs.writeFile(path.join(output, 'client.js'), client);
  await fs.writeFile(path.join(output, 'theme.config.json'), JSON.stringify({ ...config, wallpaper: asset }, null, 2) + '\n');
  return { output, imageBytes: bytes.length, kind: type.kind, mime: type.mime, duration: type.duration, version: manifest.version };
}

async function main(args) {
  const options = {};
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--help') {
      console.log('node scripts/build-theme.mjs [--media /path/to/image-or-video] [--out /path/to/bundle]\nJPEG / PNG / GIF / WebP; MP4 / WebM up to 4 seconds. --image remains supported.\nEdit theme.config.json to adjust darkening, panel opacity and blur. No dependencies or network access.');
      return;
    }
    if (!['--image', '--media', '--out'].includes(args[i]) || !args[i + 1] || args[i + 1].startsWith('--')) throw new Error(`Unknown or incomplete option: ${args[i]}`);
    options[args[i].slice(2)] = args[++i];
  }
  console.log(JSON.stringify(await buildTheme(options), null, 2));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).catch(error => { console.error(error.message); process.exitCode = 1; });
}
